// Generates src/core/standard-font-data.ts from Adobe's Core 14 AFM files.
//
// Usage: node scripts/generate-standard-font-data.mjs <afm-dir> <encodings.json> > src/core/standard-font-data.ts
//
// <afm-dir> holds the 14 AFM files (Helvetica.afm, Times-Roman.afm, ...) as published by Adobe.
// <encodings.json> maps Unicode code points to character codes for the three encodings, in the
// form { win1252: { "<unicode>": [code, glyphName] }, symbol: {...}, zapfdingbats: {...} }.
import { readFileSync } from "node:fs";
import { join } from "node:path";

const [afmDir, encodingsFile] = process.argv.slice(2);
if (!afmDir || !encodingsFile) {
  console.error("usage: generate-standard-font-data.mjs <afm-dir> <encodings.json>");
  process.exit(1);
}

const encodings = JSON.parse(readFileSync(encodingsFile, "utf8"));

const FONTS = [
  ["Helvetica", "Helvetica", "win1252"],
  ["HelveticaBold", "Helvetica-Bold", "win1252"],
  ["HelveticaOblique", "Helvetica-Oblique", "win1252"],
  ["HelveticaBoldOblique", "Helvetica-BoldOblique", "win1252"],
  ["TimesRoman", "Times-Roman", "win1252"],
  ["TimesBold", "Times-Bold", "win1252"],
  ["TimesItalic", "Times-Italic", "win1252"],
  ["TimesBoldItalic", "Times-BoldItalic", "win1252"],
  ["Courier", "Courier", "win1252"],
  ["CourierBold", "Courier-Bold", "win1252"],
  ["CourierOblique", "Courier-Oblique", "win1252"],
  ["CourierBoldOblique", "Courier-BoldOblique", "win1252"],
  ["Symbol", "Symbol", "symbol"],
  ["ZapfDingbats", "ZapfDingbats", "zapfdingbats"],
];

function parseAfm(file) {
  const header = {};
  const widthByName = new Map();
  for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
    const metric = /^C\s+-?\d+\s*;\s*WX\s+(-?\d+)\s*;\s*N\s+(\S+)/.exec(line);
    if (metric) {
      widthByName.set(metric[2], Number(metric[1]));
      continue;
    }
    const [key, ...rest] = line.trim().split(/\s+/);
    if (key && !(key in header)) header[key] = rest;
  }
  return { header, widthByName };
}

const out = [];
out.push(`// Generated by scripts/generate-standard-font-data.mjs. Do not edit by hand.
//
// Metrics for the 14 standard PDF fonts, derived from the Adobe Core 14 AFM files:
//
//   Copyright (c) 1985, 1987, 1989, 1990, 1997 Adobe Systems Incorporated. All Rights Reserved.
//
//   This file and the 14 PostScript(R) AFM files it accompanies may be used, copied, and
//   distributed for any purpose and without charge, with or without modification, provided
//   that all copyright notices are retained; that the AFM files are not distributed without
//   this file; that all modifications to this file or any of the AFM files are prominently
//   noted in the modified file(s); and that this paragraph is not modified. Adobe Systems has
//   no responsibility or obligation to support the use of the AFM files.
//
// Modification notice: the AFM files were reduced to the header values and advance widths
// below, indexed by character code in the encoding each font is used with. Kerning pairs and
// glyph bounding boxes were dropped.
//
// Helvetica and Times are trademarks of Linotype-Hell AG and/or its subsidiaries. ITC Zapf
// Dingbats is a registered trademark of International Typeface Corporation.

export interface StandardFontData {
  /** The PostScript name, used as \`BaseFont\`. */
  readonly name: string;
  readonly encoding: "win1252" | "symbol" | "zapfdingbats";
  /** Everything below is in thousandths of the font size. */
  readonly ascender: number;
  readonly descender: number;
  readonly capHeight: number;
  readonly xHeight: number;
  readonly bbox: readonly [number, number, number, number];
  readonly italicAngle: number;
  readonly underlinePosition: number;
  readonly underlineThickness: number;
  /**
   * Advance widths for character codes 32–255, comma-separated; empty where the encoding has
   * no glyph. A single number means every glyph has that width.
   */
  readonly widths: string;
}

/** Flat pairs of Unicode code point and character code. */
export interface StandardEncodingData {
  readonly pairs: readonly number[];
}
`);

for (const [key, table] of Object.entries(encodings)) {
  const pairs = Object.entries(table)
    .map(([unicode, [code]]) => [Number(unicode), code])
    .sort((a, b) => a[0] - b[0]);
  for (const [, code] of pairs) {
    if (code < 32 || code > 255) throw new Error(`${key}: code ${code} out of range`);
  }
  out.push(
    `export const ${key}Encoding: StandardEncodingData = {\n  // biome-ignore format: generated data\n  pairs: [${pairs.flat().join(",")}],\n};\n`,
  );
}

for (const [exportName, psName, encoding] of FONTS) {
  const { header, widthByName } = parseAfm(join(afmDir, `${psName}.afm`));
  const widths = new Array(224).fill("");
  for (const [code, glyph] of Object.values(encodings[encoding])) {
    const width = widthByName.get(glyph);
    if (width === undefined) throw new Error(`${psName}: no width for glyph ${glyph}`);
    widths[code - 32] = String(width);
  }
  const distinct = new Set(widths.filter((w) => w !== ""));
  const packed = distinct.size === 1 ? [...distinct][0] : widths.join(",");
  const bbox = header.FontBBox.map(Number);
  const num = (key, fallback) => (header[key] ? Number(header[key][0]) : fallback);
  out.push(`export const ${exportName}Data: StandardFontData = {
  name: "${psName}",
  encoding: "${encoding}",
  ascender: ${num("Ascender", bbox[3])},
  descender: ${num("Descender", bbox[1])},
  capHeight: ${num("CapHeight", bbox[3])},
  xHeight: ${num("XHeight", 0)},
  bbox: [${bbox.join(", ")}],
  italicAngle: ${num("ItalicAngle", 0)},
  underlinePosition: ${num("UnderlinePosition", -100)},
  underlineThickness: ${num("UnderlineThickness", 50)},
  widths:
    "${packed}",
};
`);
}

process.stdout.write(out.join("\n"));
